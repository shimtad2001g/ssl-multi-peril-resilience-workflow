    fig.update_layout(
        title="Crop Health (NDVI) vs Rainfall",
        yaxis=dict(title='NDVI', range=[0, 1]),
        yaxis2=dict(title='Rainfall (mm)', overlaying='y', side='right'),
        legend=dict(x=0.01, y=0.99)
    )
    st.plotly_chart(fig, width='stretch')

